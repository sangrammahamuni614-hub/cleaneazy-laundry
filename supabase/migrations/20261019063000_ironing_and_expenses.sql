-- CleanEazy Laundry: independent ironing rates and expense ledger.
-- Additive only: existing services, orders, payments and rate snapshots are preserved.

insert into public.services (service_name, unit_type, rate, active, is_deleted)
select v.service_name, v.unit_type, v.rate, true, false
from (values
  ('फक्त इस्त्री — सामान्य कपडे', 'piece', 10.00::numeric),
  ('फक्त इस्त्री — साडी', 'piece', 60.00::numeric)
) as v(service_name, unit_type, rate)
where not exists (
  select 1 from public.services s
  where lower(trim(s.service_name)) = lower(trim(v.service_name))
    and coalesce(s.is_deleted, false) = false
);

create table if not exists public.business_expenses (
  id bigint generated by default as identity primary key,
  expense_date date not null default current_date,
  category text not null check (category in ('दुकानभाडे','वीज','धुलाई साहित्य','पगार','पिकअप/डिलिव्हरी','दुरुस्ती','इतर')),
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null default 'Cash' check (payment_method in ('Cash','UPI','Card','Bank Transfer','Other')),
  reference_number text,
  notes text,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now()
);

create index if not exists business_expenses_date_idx on public.business_expenses(expense_date desc, id desc);
alter table public.business_expenses enable row level security;
grant select, insert, update on public.business_expenses to authenticated;
grant usage, select on sequence public.business_expenses_id_seq to authenticated;
drop policy if exists "CleanEazy admins manage expenses" on public.business_expenses;
create policy "CleanEazy admins manage expenses"
  on public.business_expenses for all to authenticated
  using ((select private.is_admin()))
  with check ((select private.is_admin()));
revoke delete on public.business_expenses from anon, authenticated;
